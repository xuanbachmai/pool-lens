/*
 * Generate js/categories.js — the project -> category map the screener groups by.
 *
 * DefiLlama's yields endpoint has no category field; the categories live on the protocols
 * endpoint, joined by project slug. That join is exact (all 498 projects and all 16,754 pools
 * matched when this was written), but the protocols response is 9.1 MB, which is not something
 * to pull into a browser alongside the 2.4 MB pool dataset just to label a row.
 *
 * So the map is baked instead. Category strings are de-duplicated into an index, which takes it
 * from 13 KB to about 9 KB, and projects added to DefiLlama after a build fall through to the
 * runtime fallback in js/categories.js rather than vanishing.
 *
 *   node tools/build-categories.mjs
 */
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'js', 'categories.js');

async function get(url) {
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

console.log('fetching pools…');
const poolsRaw = await get('https://yields.llama.fi/pools');
const pools = poolsRaw.data || poolsRaw;

console.log('fetching protocols…');
const protocols = await get('https://api.llama.fi/protocols');

const bySlug = new Map();
for (const p of protocols) if (p.slug) bySlug.set(p.slug, p.category || null);

// Only projects that actually appear in the yields data — the rest would be dead weight.
const used = new Map();
let matched = 0;
for (const p of pools) {
  if (used.has(p.project)) continue;
  const cat = bySlug.get(p.project) || null;
  if (cat) matched++;
  used.set(p.project, cat);
}

const categories = [...new Set([...used.values()].filter(Boolean))].sort();
const index = new Map(categories.map((c, i) => [c, i]));

const map = {};
for (const [slug, cat] of [...used.entries()].sort()) {
  if (cat) map[slug] = index.get(cat);
}

console.log(`${used.size} projects, ${matched} with a category, ${categories.length} distinct`);

const body = `/*
 * Project -> category, baked from DefiLlama's protocols endpoint.
 *
 * GENERATED by tools/build-categories.mjs — do not edit by hand. Regenerate when new projects
 * appear; anything missing falls through to the inference below rather than disappearing.
 *
 * Built ${new Date().toISOString().slice(0, 10)} from ${used.size} projects across ${categories.length} categories.
 */
window.LP = window.LP || {};

LP.categories = (function () {
  const NAMES = ${JSON.stringify(categories)};

  // slug -> index into NAMES.
  const MAP = ${JSON.stringify(map)};

  /*
   * Broad groups, because 42 categories is a filter nobody reads. The raw DefiLlama category is
   * kept alongside, so the detail is still there for anyone who wants it.
   */
  const GROUPS = {
    'DEX': ['Dexs', 'Liquidity Manager', 'DEX Aggregator'],
    'Lending': ['Lending', 'Uncollateralized Lending', 'Risk Curators', 'CDP', 'Leveraged Farming'],
    'Liquid staking': ['Liquid Staking', 'Liquid Restaking', 'Restaking'],
    'Yield': ['Yield', 'Yield Aggregator', 'Farm', 'Basis Trading', 'Yield Lottery'],
    'Stablecoins': ['Algo-Stables', 'Dual-Token Stablecoin', 'Stablecoin Issuer'],
    'RWA': ['RWA', 'RWA Lending'],
    'Derivatives': ['Derivatives', 'Options', 'Options Vault', 'Prediction Market'],
    'Managed': ['Onchain Capital Allocator', 'Treasury Manager', 'Portfolio Manager']
  };

  const GROUP_OF = (() => {
    const m = {};
    for (const [g, cats] of Object.entries(GROUPS)) for (const c of cats) m[c] = g;
    return m;
  })();

  /** The raw DefiLlama category for a project slug, or null if it is not in the baked map. */
  function raw(project) {
    const i = MAP[project];
    return i === undefined ? null : NAMES[i];
  }

  /**
   * The category for a pool, with a fallback for projects added since the last build.
   *
   * The fallback leans on what the app already knows: if our own fee table recognises the
   * project as an AMM, it is a DEX whatever DefiLlama has not yet told us.
   */
  function of(pool) {
    const direct = raw(pool.project);
    if (direct) return direct;
    if (window.LP && LP.fees) {
      const t = LP.fees.profileFor(pool.project).type;
      if (t === 'cpmm' || t === 'cl' || t === 'stable' || t === 'weighted') return 'Dexs';
    }
    return 'Other';
  }

  /** The broad group a category belongs to. */
  const group = (category) => GROUP_OF[category] || 'Other';

  /** Every category present in a set of pools, with counts, biggest first. */
  function present(pools) {
    const counts = new Map();
    for (const p of pools) {
      const c = p.category || of(p);
      counts.set(c, (counts.get(c) || 0) + 1);
    }
    return [...counts.entries()]
      .map(([category, n]) => ({ category, n, group: group(category) }))
      .sort((a, b) => b.n - a.n);
  }

  return { of, raw, group, present, NAMES, GROUPS,
           size: Object.keys(MAP).length };
})();
`;

await writeFile(OUT, body);
console.log(`wrote ${OUT} (${(body.length / 1024).toFixed(1)} KB)`);
